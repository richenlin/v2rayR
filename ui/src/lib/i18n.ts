const dictionaries: Record<Lang, Record<string, string>> = {
  "zh-cn": zh,
  "en-us": en,
};

export function resolveLang(language: string | undefined): Lang {
  if (language === "zh-cn" || language === "en-us") return language;
  if (typeof navigator !== "undefined" && !navigator.language.toLowerCase().startsWith("zh")) {
    return "en-us";
  }
  return "zh-cn";
}

export function translate(
  lang: Lang,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const template = dictionaries[lang][key] ?? dictionaries["zh-cn"][key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    vars[name] === undefined ? `{${name}}` : String(vars[name]),
  );
}

/** Human text for a problem: translated code, then the backend detail. */
export function problemText(
  lang: Lang,
  problem: { code: string; key: string; detail?: string } | undefined,
): string {
  if (!problem) return "";
  const translated = translate(lang, `error.${problem.code}`);
  const label = translated === `error.${problem.code}` ? problem.code : translated;
  return problem.detail ? `${label}：${problem.detail}` : label;
}
